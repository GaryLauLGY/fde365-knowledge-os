import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtemp, mkdir, readFile, writeFile, access } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
if (process.platform !== "darwin") throw new Error("macOS only");
const version = JSON.parse(await readFile("manifest.json", "utf8")).version;
function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { encoding: "utf8", timeout: 60000, ...opts });
  assert.equal(r.status, 0, r.error?.message || r.stderr || r.stdout);
  return r;
}
run(process.execPath, ["scripts/check-mac-installer.mjs"]);
run(process.execPath, ["scripts/package-mac-installer.mjs"]);
const qa = await mkdtemp(join(tmpdir(), "fde365-mac-account-qa-"));
const home = join(qa, "home");
const vault = join(home, "Documents/FDE365工作台");
const bundle = join(qa, "FDE365-Knowledge-OS-Mac-v" + version);
const originals = { ".claude/settings.json": '{"keep":"claude"}\n', ".codex/config.toml": 'model = "keep"\n', ".zshrc": "export KEEP_ME=1\n" };
for (const [path, content] of Object.entries(originals)) {
  await mkdir(join(home, path, ".."), { recursive: true });
  await writeFile(join(home, path), content);
}
run("/usr/bin/unzip", ["-q", "mac-release/FDE365-Knowledge-OS-Mac-v" + version + ".zip", "-d", qa]);
const env = { ...process.env, HOME: home, FDE365_SIMULATION: "1" };
const installed = run("/bin/bash", [join(bundle, "开始安装 FDE365.command")], { env, input: "4\n" + vault + "\n\n" });
assert.match(installed.stdout, /安装完成/);
assert.match(installed.stdout, /已跳过打开 Obsidian/);
const dataPath = join(vault, ".obsidian/plugins/fde365-knowledge-os/data.json");
const data = JSON.parse(await readFile(dataPath, "utf8"));
assert.equal(data.schemaVersion, 5);
assert.equal(data.ai.fde365.model, "gpt-5.6-luna");
assert.ok(!data.ai.fde365.token);
assert.ok(!data.account?.accessToken);
const skills = JSON.parse(await readFile(join(vault, "FDE365知识库/fde-manifest.json"), "utf8"));
assert.equal(skills.skills.length + skills.new_skills.length, 34);
await assert.rejects(access(join(vault, "FDE365知识库/.agents/skills/fde-connect")));
await assert.rejects(access(join(home, ".local/bin/claude")));
await assert.rejects(access(join(home, "Desktop/FDE365 工具/打开 FDE365 Codex.command")));
await access(join(home, ".local/bin/codex"));
run("/bin/bash", [join(bundle, "检查安装.command")], { env, input: "\n" });
const dataBeforeUpdate = await readFile(dataPath, "utf8");
const notePath = join(vault, "user-note.md");
await writeFile(notePath, "user content stays\n");
run("/bin/bash", [join(bundle, "更新 FDE365.command")], { env, input: vault + "\n\n" });
assert.equal(await readFile(dataPath, "utf8"), dataBeforeUpdate);
assert.equal(await readFile(notePath, "utf8"), "user content stays\n");
for (const [path, content] of Object.entries(originals)) assert.equal(await readFile(join(home, path), "utf8"), content);
console.log("PASS Mac install + update: 34 skills, no credentials, no global client writes, user data preserved; no real app launch.");
console.log("QA directory: " + qa);
