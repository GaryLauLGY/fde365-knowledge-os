import assert from "node:assert/strict";
import { access, readFile } from "node:fs/promises";
const root = "installer/windows";
for (const f of ["开始安装 FDE365.cmd", "开始安装 FDE365.ps1", "更新 FDE365.cmd", "更新 FDE365.ps1", "检查安装.cmd", "检查安装.ps1", "打开 FDE365 知识库.cmd", "使用说明.md", "⭐ 先看我.html"]) await access(root + "/" + f);
const install = await readFile(root + "/开始安装 FDE365.ps1", "utf8");
const common = await readFile(root + "/helpers/FDE365.Common.ps1", "utf8");
for (const required of ["https://api.ipzsk.com/v1", "Write-FdeVaultPointer", "Write-FdePluginSettings", "Install-FdeOfficialApplications"]) assert.ok(install.includes(required), required);
for (const required of ["https://chatgpt.com/codex/install.ps1", "Get-AuthenticodeSignature", "Get-FileHash", "Copy-FdeCreateOnly", "FDE365_SIMULATION"]) assert.ok(common.includes(required), required);
assert.doesNotMatch(install + common, /Get-FdeTokenFromPrompt|Write-FdeClientConfig|"\.claude|"\.codex|ANTHROPIC_BASE_URL|FDE365_TOKEN_INPUT|claude.ai\/install/);
assert.doesNotMatch(install + common, /SetEnvironmentVariable\([^\n]+["']User["']/i);
const update = await readFile(root + "/更新 FDE365.ps1", "utf8");
assert.match(update, /用户数据已保留/);
assert.doesNotMatch(update, /Remove-Item[^\n]+pluginTarget/i);
const release = JSON.parse(await readFile(root + "/obsidian-release.json", "utf8"));
assert.match(release.windowsUrl, /^https:\/\/fdekb.garylau.ai\/vendor\/obsidian\//);
assert.match(release.codexWindowsSha256, /^[a-f0-9]{64}$/);
console.log("PASS Windows installer preserves global clients and uses account login plus an isolated Agent.");
